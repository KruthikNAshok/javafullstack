class Flowers {
    String name;
    String color;
    String fragranceType;
    boolean isSeasonal;
    int petalsCount;
    String originCountry;

    public void printDetails() {
        System.out.println("Name: " + name);
        System.out.println("Color: " + color);
        System.out.println("Fragrance Type: " + fragranceType);
        System.out.println("Is Seasonal: " + isSeasonal);
        System.out.println("Petals Count: " + petalsCount);
        System.out.println("Origin Country: " + originCountry);
       
    }
}