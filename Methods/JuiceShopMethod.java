class JuiceShopMethod {

    public static void main(String[] args) {
        citrusJuices("Orange", "Sweet Lime");
        tropicalJuices("Mango", "Pineapple");
        mixedJuices("Fruit Punch", "ABC Juice");
        seasonalJuices("Watermelon", "Grapes");
    }

    public static void citrusJuices(String juice1, String juice2) {
        System.out.println( juice1 +  juice2);
    }

    public static void tropicalJuices(String juice1, String juice2) {
        System.out.println( juice1 + juice2);
    }

    public static void mixedJuices(String juice1, String juice2) {
        System.out.println( juice1 + juice2);
    }

    public static void seasonalJuices(String juice1, String juice2) {
        System.out.println( juice1 +  juice2);
    }
}
