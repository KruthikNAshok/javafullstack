class SpiceShopMethod {

    public static void main(String[] args) {
        wholeSpices("Clove", "Cinnamon");
        groundSpices("Turmeric", "Chili Powder");
        spiceMixes("Garam Masala", "Sambar Powder");
        aromaticSpices("Cardamom", "Star Anise");
    }

    public static void wholeSpices(String spice1, String spice2) {
        System.out.println( spice1 +  spice2);
    }

    public static void groundSpices(String spice1, String spice2) {
        System.out.println( spice1 +  spice2);
    }

    public static void spiceMixes(String spice1, String spice2) {
        System.out.println( spice1  + spice2);
    }

    public static void aromaticSpices(String spice1, String spice2) {
        System.out.println( spice1 +  spice2);
    }
}
