class Registrar {
    public static void registerProperty(String buyerName, String propertyType, String location) {
        System.out.println("Registrar is registering the property");

        System.out.println("Buyer Name: " + buyerName);
        System.out.println("Property Type: " + propertyType);
        System.out.println("Location: " + location);

        System.out.println("Property registered successfully");
    }
}
